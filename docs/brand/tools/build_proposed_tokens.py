#!/usr/bin/env python3
"""Generate ../tokens/tokens.proposed.json and tokens.proposed.css (v1.1 PROPOSED, new keys only).
Never reads-for-write or edits tokens.json / tokens.css. Python 3.9+, stdlib only."""
import json, math, pathlib
import themelib as T

root = T.ROOT
v1 = T.load_v1()
v1_vars = {c["cssVar"] for m in ("light", "dark") for c in v1["color"][m].values()}

COLOR_KEYS = T.COLOR_KEYS

def rgba(h, a):
    r, g, b = T.h2rgb(h)
    return f"rgba({r},{g},{b},{a:g})"

def entry(t, key, name, role, cssvar):
    v = t[key]
    if isinstance(v, tuple):
        return {"name": name, "hex": v[0], "alpha": v[1], "value": rgba(*v), "role": role, "cssVar": cssvar}
    return {"name": name, "hex": v, "role": role, "cssVar": cssvar}

themes = {m: T.build_theme(m) for m in ("light", "dark")}
color = {m: {k: entry(themes[m], k, n, r, c) for k, n, r, c in COLOR_KEYS} for m in themes}
for m in color:
    for e in color[m].values():
        assert e["cssVar"] not in v1_vars, "collides with a v1 variable"

SPACE = {"0.5": 4, "1": 8, "1.5": 12, "2": 16, "3": 24, "4": 32, "5": 40, "6": 48, "8": 64, "10": 80, "12": 96}
BREAK = {"compact": 0, "medium": 600, "expanded": 840, "large": 1200, "xlarge": 1600}
SHADOW = {"light": "0 8px 24px rgba(14,17,23,0.16)", "dark": "none"}

# App icon geometry: mark is the v1 quarter-disc pair. Area centroid of the two sectors vs the bounding-box centre.
def sector_area_centroid(a0, a1, R=22.5, cx=5.0, cy=27.0):
    a0r, a1r = math.radians(a0), math.radians(a1)
    area = 0.5 * R * R * (a1r - a0r)
    mx = (2 * R / 3) * (math.sin(a1r) - math.sin(a0r)) / (a1r - a0r)
    my = (2 * R / 3) * (math.cos(a0r) - math.cos(a1r)) / (a1r - a0r)
    return area, cx + mx, cy - my
A1, X1, Y1 = sector_area_centroid(0, 40); A2, X2, Y2 = sector_area_centroid(52, 90)
CX = (A1 * X1 + A2 * X2) / (A1 + A2); CY = (A1 * Y1 + A2 * Y2) / (A1 + A2)
BBOX_C = (16.25, 15.75)
FULL_CORRECTION = (BBOX_C[0] - CX, BBOX_C[1] - CY)          # mark units, +x right, +y down
SCALE = 0.56 * 64 / 22.5                                      # tile units per mark unit (v1: 56% of tile)
NUDGE_TILE = (1.5, -1.5)                                      # v1 inferred value, kept (see 11 doc)
appicon = {
    "tileSizeUnits": 64, "cornerRadiusUnits": 14, "cornerRadiusPercent": round(14 / 64 * 100, 2),
    "markFraction": 0.56, "nudgeUnitsOf64": {"x": 1.5, "y": -1.5}, "nudgePercentOfTile": round(1.5 / 64 * 100, 2),
    "areaCentroidMarkUnits": {"x": round(CX, 3), "y": round(CY, 3)},
    "fullCentroidCorrectionTileUnits": {"x": round(FULL_CORRECTION[0] * SCALE, 2), "y": round(FULL_CORRECTION[1] * SCALE, 2)},
    "nudgeAsShareOfFullCorrection": round(1.5 / (FULL_CORRECTION[0] * SCALE), 2),
    "maskableSafeRadiusFraction": 0.40, "note": "Rounded tile for web and desktop; stores that apply their own mask get a full-bleed square (tools/build_icons.py)."}

doc = {
    "$comment": "v1.1 PROPOSED additions. New keys only; v1 tokens.json is unchanged. Generated by tools/build_proposed_tokens.py. Founders accept or reject each block.",
    "status": "PROPOSED",
    "color": color,
    "naming": {
        "$comment": "v1 uses two Carbon hexes. Hex values are NOT changed; they get two names.",
        "carbonInk": {"hex": "#12151B", "role": "Text on light, one-colour mark, mono print", "cssVar": "--carbon-ink"},
        "carbonDeep": {"hex": "#0E1117", "role": "Dark background, label on light Cobalt/Crimson fills, dark app-icon tile", "cssVar": "--carbon-deep"}},
    "spacing": {"baseGridPx": 8, "halfStepsPx": [4, 12], "scale": {k: v for k, v in SPACE.items()}},
    "breakpoints": {"minWidthPx": BREAK, "note": "Media queries cannot read CSS variables; use these numbers literally."},
    "elevation": {
        "levels": {"0": "Background, no border", "1": "Surface: 1px --color-border, no shadow", "2": "Raised overlay: --color-surface-raised, 1px --color-border, --shadow-overlay (light only)"},
        "shadowOverlay": SHADOW, "shadowAllowedOn": ["menu", "popover", "modal", "drawer", "toast"], "borderWidthPx": 1,
        "scrimOpacity": {"light": 0.48, "dark": 0.64}},
    "controls": {
        "heightPx": 40, "heightCompactPx": 32, "heightTouchPx": 48, "hitTargetMinPx": 24, "borderWidthPx": 1, "errorBorderWidthPx": 2,
        "checkboxBoxPx": 20, "radioBoxPx": 20, "switch": {"trackWidthPx": 40, "trackHeightPx": 24, "thumbPx": 16},
        "textareaMinHeightPx": 96, "labelStyle": "small 500", "helperStyle": "caption 400"},
    "table": {"rowHeightPx": {"comfortable": 48, "compact": 40, "dense": 32}, "headerHeightPx": 40, "cellPaddingInlinePx": 12,
              "selectedIndicatorWidthPx": 2, "stickyHeader": True, "zebra": False},
    "navigation": {"sidebarWidthPx": 256, "sidebarCollapsedWidthPx": 72, "topBarHeightPx": 56, "navItemHeightPx": 40, "bottomBarHeightPx": 64},
    "overlays": {"modalWidthPx": {"sm": 480, "md": 640}, "drawerWidthPx": {"sm": 400, "md": 560}, "overlayPaddingPx": 24, "toastWidthPx": 360, "toastMax": 3,
                 "toastAutoDismissMs": {"success": 6000, "info": 6000, "warning": 10000, "error": None}},
    "tabs": {"heightPx": 40, "indicatorWidthPx": 2},
    "chat": {"maxMessageWidthPx": 640, "avatarPx": 24, "approvalCardRadiusPx": 12, "approvalCardPaddingPx": 16},
    "progressQuadrant": {"sectors": 4, "sectorDegrees": 22.5, "gapDegrees": 1.5, "sectorMeaning": "one week of the simulated month", "sizePx": 64},
    "device": {"opacity": T.DEVICE_OPACITY, "opacityMaxNoOverlapText": T.DEVICE_OPACITY_MAX, "radiusMinShareOfShortSide": 0.6,
               "radiusMaxShareOfShortSide": 1.0, "rotationStepDegrees": 90, "perView": 1, "radiusPx": 0},
    "chart": {"maxSeries": 6, "minNonTextContrast": 3.0, "minPairwiseDeltaEOklabCvd": 0.08, "seriesPatterns": ["solid", "diagonal-hatch", "dots", "cross-hatch", "reverse-hatch", "dashed-outline"],
              "comparisonAlpha": {"light": themes["light"]["_comparison_alpha"], "dark": themes["dark"]["_comparison_alpha"]},
              "v1ComparisonAlpha": 0.40, "markers": ["circle", "square", "triangle", "diamond", "cross", "ring"]},
    "appIcon": appicon,
    "destructive": {"v1": {"light": {"fill": "#C21F3A", "label": "#FFFFFF"}, "dark": {"fill": "#FF6B81", "label": "#FFFFFF"}},
                    "proposed": {"light": {"fill": "#C21F3A", "label": "#FFFFFF"}, "dark": {"fill": "#FF6B81", "label": "#0E1117"}}},
    "icons": {"sizesPx": [24, 20], "strokePx": 1.75, "strokeAbsoluteAt20": True},
}
(root / "tokens" / "tokens.proposed.json").write_text(json.dumps(doc, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

# ---------- CSS ----------
def cssval(e):
    return e["value"] if "value" in e else e["hex"]

def block(m, ind):
    return "".join(f"{ind}{e['cssVar']}: {cssval(e)};\n" for e in color[m].values()) + f"{ind}--shadow-overlay: {SHADOW[m]};\n"

o = ["/* GENERATED by tools/build_proposed_tokens.py. v1.1 PROPOSED: new variables only, load AFTER tokens.css. Do not edit by hand. */\n:root {\n"]
o.append(block("light", "  "))
o.append("  --carbon-ink: #12151B;\n  --carbon-deep: #0E1117;\n")
for k, v in SPACE.items():
    o.append(f"  --space-{k.replace('.', '_')}: {v}px;\n")
for k, v in BREAK.items():
    o.append(f"  --bp-{k}: {v}px;\n")
c, tb, nv, ov = doc["controls"], doc["table"], doc["navigation"], doc["overlays"]
o.append(f"  --control-height: {c['heightPx']}px;\n  --control-height-compact: {c['heightCompactPx']}px;\n  --control-height-touch: {c['heightTouchPx']}px;\n  --hit-target-min: {c['hitTargetMinPx']}px;\n")
o.append(f"  --border-width: {c['borderWidthPx']}px;\n  --border-width-error: {c['errorBorderWidthPx']}px;\n")
o.append(f"  --row-comfortable: {tb['rowHeightPx']['comfortable']}px;\n  --row-compact: {tb['rowHeightPx']['compact']}px;\n  --row-dense: {tb['rowHeightPx']['dense']}px;\n  --table-header-height: {tb['headerHeightPx']}px;\n")
o.append(f"  --sidebar-width: {nv['sidebarWidthPx']}px;\n  --sidebar-width-collapsed: {nv['sidebarCollapsedWidthPx']}px;\n  --topbar-height: {nv['topBarHeightPx']}px;\n")
o.append(f"  --modal-width-sm: {ov['modalWidthPx']['sm']}px;\n  --modal-width-md: {ov['modalWidthPx']['md']}px;\n  --drawer-width-sm: {ov['drawerWidthPx']['sm']}px;\n  --drawer-width-md: {ov['drawerWidthPx']['md']}px;\n  --toast-width: {ov['toastWidthPx']}px;\n")
o.append(f"  --device-opacity: {T.DEVICE_OPACITY};\n  --device-opacity-max: {T.DEVICE_OPACITY_MAX};\n")
o.append("}\n\n@media (prefers-color-scheme: dark) {\n  :root:not([data-theme=\"light\"]) {\n" + block("dark", "    ") + "  }\n}\n\n")
o.append(":root[data-theme=\"dark\"] {\n" + block("dark", "  ") + "}\n")
(root / "tokens" / "tokens.proposed.css").write_text("".join(o), encoding="utf-8")
print("wrote tokens.proposed.json and tokens.proposed.css;", len(COLOR_KEYS), "colour keys per mode")
print("area centroid (mark units):", round(CX, 3), round(CY, 3), "full correction (tile units of 64):", appicon["fullCentroidCorrectionTileUnits"], "nudge share:", appicon["nudgeAsShareOfFullCorrection"])
print("comparison alpha light/dark:", themes["light"]["_comparison_alpha"], themes["dark"]["_comparison_alpha"])
