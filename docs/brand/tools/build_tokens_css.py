#!/usr/bin/env python3
"""Generate ../tokens/tokens.css from ../tokens/tokens.json (stdlib only)."""
import json, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
t = json.loads((root / "tokens" / "tokens.json").read_text(encoding="utf-8"))
order = ["background", "surface", "text", "primary", "accent", "success", "warning", "danger"]

def colors(mode, ind):
    return "".join(f"{ind}{t['color'][mode][k]['cssVar']}: {t['color'][mode][k]['hex']};\n" for k in order)

ty = t["typography"]
o = ["/* GENERATED by tools/build_tokens_css.py from tokens.json. Do not edit by hand. */\n"]
o.append(":root {\n" + colors("light", "  "))
o.append(f"  --font-heading: \"{ty['families']['heading']['family']}\", {ty['families']['heading']['fallback']};\n")
o.append(f"  --font-body: \"{ty['families']['body']['family']}\", {ty['families']['body']['fallback']};\n")
for name, s in ty["scale"].items():
    o.append(f"  --text-{name}-size: {s['latin']['size']}px;\n  --text-{name}-line: {s['latin']['lineHeight']}px;\n  --text-{name}-weight: {s['weight']};\n")
    o.append(f"  --text-{name}-line-ar: {s['arabic']['lineHeight']}px;\n")
o.append(f"  --space-unit: {t['spacing']['baseGridPx']}px;\n")
o.append(f"  --radius-control: {t['radius']['controlPx']}px;\n  --radius-card: {t['radius']['cardPanelPx']}px;\n  --radius-brand-graphic: {t['radius']['brandGraphicsPx']}px;\n")
f = t["focusRing"]
o.append(f"  --focus-ring-width: {f['widthPx']}px;\n  --focus-ring-offset: {f['offsetPx']}px;\n")
m = t["motion"]
o.append(f"  --motion-fast: {m['durationMsMin']}ms;\n  --motion-slow: {m['durationMsMax']}ms;\n  --motion-ease: {m['easing']};\n")
o.append(f"  --button-height: {t['components']['primaryButton']['heightPx']}px;\n")
o.append(f"  --status-tint-opacity: {t['components']['statusPill']['tintOpacity']};\n")
o.append("}\n\n")
o.append("@media (prefers-color-scheme: dark) {\n  :root:not([data-theme=\"light\"]) {\n" + colors("dark", "    ") + "  }\n}\n\n")
o.append(":root[data-theme=\"dark\"] {\n" + colors("dark", "  ") + "}\n\n")
o.append("/* Arabic line heights (PDF p.9: same sizes, more line height) */\n[dir=\"rtl\"] {\n")
for name in ty["scale"]:
    o.append(f"  --text-{name}-line: var(--text-{name}-line-ar);\n")
o.append("}\n\n@media (prefers-reduced-motion: reduce) {\n  :root { --motion-fast: 0ms; --motion-slow: 0ms; }\n}\n")
(root / "tokens" / "tokens.css").write_text("".join(o), encoding="utf-8")
print("wrote tokens.css")
