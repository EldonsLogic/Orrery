// Generates the branding preview's colour data from the canonical token file (docs/brand/tokens/tokens.json),
// so the screen never keeps its own copy of the base colours (WEB-007). Never hand-edit the output.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
export const SOURCE = resolve(here, '../../docs/brand/tokens/tokens.json');
export const TARGET = resolve(here, '../app/src/settings/branding/colour.tokens.generated.json');

const KEYS = ['background', 'surface', 'text', 'danger'];

export function buildBrandingColours(tokens) {
  const c = tokens.color;
  const base = {};
  for (const mode of ['light', 'dark']) base[mode] = Object.fromEntries(KEYS.map((k) => [k, c[mode][k].hex]));
  return {
    _generated: 'Generated by web/scripts/gen-branding-colours.mjs from docs/brand/tokens/tokens.json. Do not edit by hand.',
    defaultPrimary: c.light.primary.hex,
    base,
  };
}

export const renderBrandingColours = (tokens) => JSON.stringify(buildBrandingColours(tokens), null, 2) + '\n';

export function writeBrandingColours() {
  writeFileSync(TARGET, renderBrandingColours(JSON.parse(readFileSync(SOURCE, 'utf8'))));
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) writeBrandingColours();
